import React, { useCallback, useEffect, useRef, useState } from "react";
import { api, money, monthAdd, monthLabel, pct, statusColor } from "../api.js";
import { useApp } from "../App.jsx";
import { ErrorBox, MemberPills, Meter } from "../components/ui.jsx";

export default function Forecast() {
  const { me, household, hid, refreshHousehold } = useApp();
  const maxMonth = household.forecast_month;
  const minMonth = household.first_month ? monthAdd(household.first_month, 1) : maxMonth;
  const [month, setMonth] = useState(maxMonth);
  const [fc, setFc] = useState(null);
  const [recs, setRecs] = useState(null);
  const [revealed, setRevealed] = useState(false);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(true);
  const req = useRef(0);
  const cur = household.currency;
  const canEdit = household.my_role !== "viewer";

  const load = useCallback(async (refresh = false) => {
    const id = ++req.current;
    setLoading(true); setError("");
    try {
      const f = await api(`/households/${hid}/forecast/${month}`);
      if (id !== req.current) return;
      setFc(f);
      setRecs(null);
      const r = await api(`/households/${hid}/recommendations/${month}${refresh ? "?refresh=true" : ""}`);
      if (id === req.current) setRecs(r);
    } catch (e) { if (id === req.current) setError(e.message); }
    finally { if (id === req.current) setLoading(false); }
  }, [hid, month]);

  useEffect(() => { load(); }, [load]);
  useEffect(() => { refreshHousehold(); }, []);  // eslint-disable-line
  useEffect(() => { setRevealed(false); }, [month]);

  const savePlan = async (cat, value) => {
    const v = parseFloat(value);
    if (!(v >= 0)) return;
    try { await api(`/households/${hid}/budgets/${month}`, { method: "PUT", body: { amounts: { [cat]: v } } }); load(); }
    catch (e) { setError(e.message); }
  };
  const agree = async (agreed) => {
    try { const a = await api(`/households/${hid}/agreement/${month}`, { method: "PUT", body: { agreed } }); setFc({ ...fc, agreement: a }); }
    catch (e) { setError(e.message); }
  };

  const total = fc?.total, plan = fc?.plan_total;
  const diff = total && plan ? ((total - plan) / plan) * 100 : null;
  const actualTotal = fc?.categories?.every((c) => c.actual !== null) ? fc.categories.reduce((s, c) => s + c.actual, 0) : null;
  const ag = fc?.agreement;

  return (
    <div className="wrap">
      <div className="note">
        <b>How forecasts work.</b> Each category is forecast from this household's own monthly totals before the selected month.
        Until there is enough history, a simpler rule is used and marked “low confidence”.
        {recs ? (recs.source === "llm" ? " Recommendations are generated by an AI language model from these forecasts." : " Recommendations below are rule-based.") : ""}
        {" "}Decision support only, not professional financial advice.
      </div>

      <header className="page">
        <div>
          <div className="eyebrow">Shared household budget</div>
          <h1>{household.name}</h1>
          <div className="sub">{household.members.length} member{household.members.length !== 1 ? "s" : ""} plan one monthly budget together</div>
        </div>
        <MemberPills agreement={ag} meId={me.id} canAgree={canEdit} onToggle={agree} />
      </header>

      <div className="bar">
        <div className="stepper">
          <button aria-label="Previous month" disabled={month <= minMonth} onClick={() => setMonth(monthAdd(month, -1))}>←</button>
          <div className="month"><div className="eyebrow">Forecast for</div><span>{monthLabel(month)}</span></div>
          <button aria-label="Next month" disabled={month >= maxMonth} onClick={() => setMonth(monthAdd(month, 1))}>→</button>
        </div>
        <button className="primary" disabled={!fc?.month_is_past} onClick={() => setRevealed(!revealed)}
          title={fc?.month_is_past ? "" : "Actual spending is available for months that are complete"}>
          {revealed ? "Hide actual spending" : "Show actual spending"}
        </button>
      </div>

      <ErrorBox error={error} />
      {loading && !fc && <p className="sub">Calculating forecasts…</p>}

      {fc && (
        <>
          <div className="summary">
            <div className="sum"><div className="eyebrow">Shared plan</div><div className="v">{money(plan, cur)}</div></div>
            <div className="sum"><div className="eyebrow">AI forecast</div><div className="v">{money(total, cur)}</div>
              {fc.total_low !== null && <div className="small-muted">likely {money(fc.total_low, cur)} – {money(fc.total_high, cur)}</div>}</div>
            <div className="sum"><div className="eyebrow">Forecast vs plan</div>
              <div className="v" style={{ color: diff === null ? "var(--muted)" : diff > 5 ? "var(--over)" : diff < -5 ? "var(--under)" : "var(--ok)" }}>{pct(diff)}</div></div>
          </div>

          {fc.history_months === 0 && (
            <div className="note"><b>No data yet.</b> Add expenses for at least one month before {monthLabel(month)} to get a forecast.</div>
          )}

          <div className="grid">
            {fc.categories.map((c) => (
              <div className="card" key={c.category}>
                <div className="card-head">
                  <h3>{c.category}</h3>
                  <span className={`chip ${c.status}`}>{c.status_label}{c.vs_plan_pct !== null ? " " + pct(c.vs_plan_pct) : ""}</span>
                </div>
                <div className="nums">
                  <div><div className="eyebrow">Forecast</div><div className="v big">{money(c.forecast, cur)}</div></div>
                  <div><div className="eyebrow">Plan{c.plan_suggested && c.plan !== null ? " (suggested)" : ""}</div><div className="v">{money(c.plan, cur)}</div></div>
                  <div><div className="eyebrow">Last month</div><div className="v">{money(c.last_month, cur)}</div></div>
                </div>
                <Meter value={c.forecast} plan={c.plan} color={statusColor(c.status)} />
                {c.forecast !== null && (
                  <div className="small-muted">
                    Likely range <b>{money(c.low, cur)} – {money(c.high, cur)}</b>
                    {c.confidence === "low" && <> · <span className="chip warn" title={c.confidence_note}>Low confidence</span></>}
                  </div>
                )}
                {c.confidence === "low" && c.confidence_note && <div className="sub">{c.confidence_note}</div>}
                <div className="rec">
                  <span className="eyebrow">Recommendation{recs ? (recs.source === "llm" ? " · AI generated" : " · rule-based") : ""}</span>
                  {recs ? recs.items[c.category] : <span className="sub">Generating…</span>}
                </div>
                <PlanEdit key={`${month}-${c.category}-${c.plan}`} id={`plan-${c.category}`} value={c.plan} disabled={!canEdit}
                  onSave={(v) => savePlan(c.category, v)} />
                {revealed && c.actual !== null && (
                  <div className="small-muted">Actual: <b>{money(c.actual, cur)}</b> · forecast error {money(c.actual - c.forecast, cur)}</div>
                )}
              </div>
            ))}

            <div className="card">
              <div className="card-head"><h3>Group decision</h3>
                <span className={`chip ${ag?.final ? "ok" : "under"}`}>{ag?.agreed_count} of {ag?.voters} agreed</span></div>
              <div className="nums">
                <div><div className="eyebrow">Shared plan</div><div className="v big">{money(plan, cur)}</div></div>
                <div><div className="eyebrow">AI forecast</div><div className="v">{money(total, cur)}</div></div>
                <div><div className="eyebrow">Gap</div><div className="v">{total !== null && plan ? money(total - plan, cur) : "—"}</div></div>
              </div>
              <div className="rec"><span className="eyebrow">How it works</span>
                Each member reviews the forecasts, adjusts category plans if needed and ticks “agrees” at the top.
                The plan for {monthLabel(month)} is final when all members agree. Changing a plan resets the agreement.</div>
              <div className="sub">{ag?.members.filter((m) => m.agreed).map((m) => m.name).join(", ") ? "Agreed: " + ag.members.filter((m) => m.agreed).map((m) => m.name).join(", ") : "Nobody has agreed yet."}</div>
              {canEdit && <button onClick={() => load(true)} disabled={loading}>↻ Regenerate recommendations</button>}
            </div>
          </div>

          <footer className="foot">
            Plans without a saved value are suggested from the last three months. Forecasts are one month ahead and use only completed months before {monthLabel(month)}{fc.latest_month ? ` (data up to ${monthLabel(fc.latest_month)})` : ""}.
            {recs?.note ? " " + recs.note : ""}{recs?.model ? ` Model: ${recs.model}.` : ""}
            {revealed && actualTotal !== null ? ` Actual total this month: ${money(actualTotal, cur)}.` : ""}
          </footer>
        </>
      )}
    </div>
  );
}

function PlanEdit({ id, value, disabled, onSave }) {
  const [v, setV] = useState(value ?? "");
  return (
    <label className="planedit" htmlFor={id}>Adjust shared plan
      <input id={id} type="number" min="0" step="10" value={v} disabled={disabled}
        onChange={(e) => setV(e.target.value)}
        onBlur={() => { if (String(v) !== String(value ?? "") && v !== "") onSave(v); }}
        onKeyDown={(e) => { if (e.key === "Enter") e.currentTarget.blur(); }} />
    </label>
  );
}
